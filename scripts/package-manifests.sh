#!/usr/bin/env bash
# Write the Homebrew formula, Scoop manifest and winget manifests for a
# published release, using the SHA-256 files attached to that release.
#
#   scripts/package-manifests.sh v0.2.0 [out-dir]
#
# Writes:
#   <out>/Formula/phygital-key.rb        (copy to the homebrew-tap repo)
#   bucket/phygital-key.json             (Scoop, served from this repo)
#   packaging/winget/<version>/*.yaml    (ready for a winget-pkgs pull request)
set -euo pipefail

version="${1:?usage: package-manifests.sh vX.Y.Z [out-dir]}"
out="${2:-dist}"
repo="s17sh70x2jfl031ag/phygital-key-mcp"
plain="${version#v}"
base="https://github.com/$repo/releases/download/$version"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

gh release download "$version" -R "$repo" -p '*.sha256' -D "$tmp"
sum() { cut -d ' ' -f 1 < "$tmp/phygital-key-$version-$1.$2.sha256"; }

mkdir -p "$out/Formula" bucket "packaging/winget/$plain"

cat > "$out/Formula/phygital-key.rb" <<EOF
# Generated by scripts/package-manifests.sh in $repo. Do not edit by hand.
class PhygitalKey < Formula
  desc "Approve exact AI actions with a passkey or hardware key (MCP gate + verifier)"
  homepage "https://github.com/$repo"
  version "$plain"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/phygital-key-$version-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum aarch64-apple-darwin tar.gz)"
    end
    on_intel do
      url "$base/phygital-key-$version-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum x86_64-apple-darwin tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$base/phygital-key-$version-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum aarch64-unknown-linux-gnu tar.gz)"
    end
    on_intel do
      url "$base/phygital-key-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum x86_64-unknown-linux-gnu tar.gz)"
    end
  end

  def install
    bin.install "phygital-key"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/phygital-key --version")
  end
end
EOF

win_sum="$(sum x86_64-pc-windows-msvc zip)"
cat > bucket/phygital-key.json <<EOF
{
    "version": "$plain",
    "description": "Approve exact AI actions with a passkey or hardware key (MCP gate + verifier)",
    "homepage": "https://github.com/$repo",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$base/phygital-key-$version-x86_64-pc-windows-msvc.zip",
            "hash": "$win_sum",
            "extract_dir": "phygital-key-$version-x86_64-pc-windows-msvc"
        }
    },
    "bin": "phygital-key.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/$repo/releases/download/v\$version/phygital-key-v\$version-x86_64-pc-windows-msvc.zip",
                "extract_dir": "phygital-key-v\$version-x86_64-pc-windows-msvc"
            }
        },
        "hash": { "url": "\$url.sha256" }
    }
}
EOF

id="PhygitalKey.PhygitalKey"
w="packaging/winget/$plain"
cat > "$w/$id.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.9.0
EOF
cat > "$w/$id.installer.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: phygital-key-$version-x86_64-pc-windows-msvc\\phygital-key.exe
    PortableCommandAlias: phygital-key
Installers:
  - Architecture: x64
    InstallerUrl: $base/phygital-key-$version-x86_64-pc-windows-msvc.zip
    InstallerSha256: $(printf '%s' "$win_sum" | tr '[:lower:]' '[:upper:]')
ManifestType: installer
ManifestVersion: 1.9.0
EOF
cat > "$w/$id.locale.en-US.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
PackageLocale: en-US
Publisher: Phygital Key contributors
PackageName: Phygital Key
License: Apache-2.0
LicenseUrl: https://github.com/$repo/blob/main/LICENSE
ShortDescription: Approve exact AI actions with a passkey or hardware key (MCP gate + verifier)
PackageUrl: https://github.com/$repo
Tags:
  - mcp
  - passkey
  - webauthn
  - security
ManifestType: defaultLocale
ManifestVersion: 1.9.0
EOF
echo "wrote $out/Formula/phygital-key.rb, bucket/phygital-key.json, $w/"
