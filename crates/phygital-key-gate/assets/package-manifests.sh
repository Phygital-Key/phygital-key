#!/usr/bin/env bash
# Write the Homebrew formula, Scoop manifest and winget manifests for a
# published release, using the SHA-256 files attached to that release.
#
#   scripts/package-manifests.sh v0.2.0 [out-dir]
#
# Writes:
#   <out>/Formula/<program>.rb        (copy to the homebrew-tap repo)
#   bucket/<program>.json             (Scoop, served from this repo)
#   packaging/winget/<version>/*.yaml    (ready for a winget-pkgs pull request)
set -euo pipefail
# Generated for one product from the template in Phygital-Key/phygital-key.
# BEGIN PRODUCT
P_NAME="Phygital Key"
P_BIN=phygital-key
P_ID=dev
P_REPO=Phygital-Key/phygital-key
P_PORT=7468
P_VERSION=v0.0.0
# END PRODUCT
bin="$P_BIN"
# Homebrew wants the class named after the file: $bin -> PhygitalKeyMcp.
class=$(printf '%s' "$bin" | awk -F- '{for (i = 1; i <= NF; i++) printf "%s%s", toupper(substr($i, 1, 1)), substr($i, 2)}')
desc="$P_NAME: approve exact AI actions with a passkey or hardware key"

version="${1:?usage: package-manifests.sh vX.Y.Z [out-dir]}"
out="${2:-dist}"
repo="$P_REPO"
plain="${version#v}"
base="https://github.com/$repo/releases/download/$version"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

gh release download "$version" -R "$repo" -p '*.sha256' -D "$tmp"
sum() { cut -d ' ' -f 1 < "$tmp/$bin-$version-$1.$2.sha256"; }

mkdir -p "$out/Formula" bucket "packaging/winget/$plain"

cat > "$out/Formula/$bin.rb" <<EOF
# Generated by scripts/package-manifests.sh in $repo. Do not edit by hand.
class $class < Formula
  desc "$desc"
  homepage "https://github.com/$repo"
  version "$plain"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/$bin-$version-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum aarch64-apple-darwin tar.gz)"
    end
    on_intel do
      url "$base/$bin-$version-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum x86_64-apple-darwin tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$base/$bin-$version-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum aarch64-unknown-linux-gnu tar.gz)"
    end
    on_intel do
      url "$base/$bin-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sum x86_64-unknown-linux-gnu tar.gz)"
    end
  end

  def install
    bin.install "$bin"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/$bin --version")
  end
end
EOF

win_sum="$(sum x86_64-pc-windows-msvc zip)"
cat > bucket/$bin.json <<EOF
{
    "version": "$plain",
    "description": "$desc",
    "homepage": "https://github.com/$repo",
    "license": "Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "$base/$bin-$version-x86_64-pc-windows-msvc.zip",
            "hash": "$win_sum",
            "extract_dir": "$bin-$version-x86_64-pc-windows-msvc"
        }
    },
    "bin": "$bin.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/$repo/releases/download/v\$version/$bin-v\$version-x86_64-pc-windows-msvc.zip",
                "extract_dir": "$bin-v\$version-x86_64-pc-windows-msvc"
            }
        },
        "hash": { "url": "\$url.sha256" }
    }
}
EOF

id="PhygitalKey.$class"
w="packaging/winget/$plain"
cat > "$w/$id.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.9.0
EOF
cat > "$w/$id.installer.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: $bin-$version-x86_64-pc-windows-msvc\\$bin.exe
    PortableCommandAlias: $bin
Installers:
  - Architecture: x64
    InstallerUrl: $base/$bin-$version-x86_64-pc-windows-msvc.zip
    InstallerSha256: $(printf '%s' "$win_sum" | tr '[:lower:]' '[:upper:]')
ManifestType: installer
ManifestVersion: 1.9.0
EOF
cat > "$w/$id.locale.en-US.yaml" <<EOF
PackageIdentifier: $id
PackageVersion: $plain
PackageLocale: en-US
Publisher: Phygital Key contributors
PackageName: $P_NAME
License: Apache-2.0
LicenseUrl: https://github.com/$repo/blob/main/LICENSE
ShortDescription: $desc
PackageUrl: https://github.com/$repo
Tags:
  - $P_ID
  - passkey
  - webauthn
  - security
ManifestType: defaultLocale
ManifestVersion: 1.9.0
EOF
echo "wrote $out/Formula/$bin.rb, bucket/$bin.json, $w/"
